"""NiceGUI web app: compare C major with the other C modes on the fretboard."""

from nicegui import events, ui

from .render import (
    CHORD_CLICK_EVENT,
    DEFAULT_STRING_SET,
    STRING_SETS,
    render_chord_table,
    render_fretboard,
    render_inversion_legend,
    render_legend,
)
from .theory import COMPARISONS, COMPARISONS_BY_KEY, Triad, triads


def root() -> None:
    """Build the single page of the app."""
    # Selected chord as (column, degree), column being "major" or "mode"; None when nothing is selected.
    selected: tuple[str, int] | None = None

    ui.label("C major and its modes").classes("text-2xl font-semibold")
    ui.label(
        "C major is the reference. Pick a mode to see which notes it alters. "
        "Click a chord in the table to see its triad shapes."
    ).classes("text-gray-600")

    with ui.row().classes("items-center gap-6"):
        comparison_select = ui.select(
            {c.key: c.label for c in COMPARISONS},
            value=COMPARISONS[0].key,
            label="Compare C major with",
        ).classes("min-w-64")
        label_toggle = ui.toggle({"degrees": "Degrees", "notes": "Note names"}, value="degrees")

    # SVG and HTML are generated by render.py from fixed data, so no sanitising is needed.
    board = ui.html(sanitize=False).classes("w-full")
    legend = ui.html(sanitize=False).classes("w-full")
    with ui.row().classes("items-center gap-6") as chord_controls:
        inversion_legend = ui.html(sanitize=False)
        string_set_toggle = ui.toggle(list(STRING_SETS), value=DEFAULT_STRING_SET)
    ui.label("Chords").classes("text-lg font-semibold mt-4")
    chords = ui.html(sanitize=False)

    def selected_triad() -> Triad | None:
        if selected is None:
            return None
        column, degree = selected
        key = "major" if column == "major" else comparison_select.value
        return triads(COMPARISONS_BY_KEY[key])[degree - 1]

    def update() -> None:
        comparison = COMPARISONS_BY_KEY[comparison_select.value]
        chord = selected_triad()
        board.content = render_fretboard(
            comparison, label_toggle.value, chord=chord, string_set=string_set_toggle.value
        )
        legend.content = render_legend(comparison)
        chords.content = render_chord_table(comparison, selected)
        chord_controls.set_visibility(chord is not None)
        inversion_legend.content = render_inversion_legend(chord) if chord else ""

    def on_comparison_change() -> None:
        nonlocal selected
        if COMPARISONS_BY_KEY[comparison_select.value].is_reference_only and selected and selected[0] == "mode":
            selected = None
        update()

    def on_chord_click(e: events.GenericEventArguments) -> None:
        nonlocal selected
        clicked = (str(e.args["column"]), int(e.args["degree"]))
        selected = None if clicked == selected else clicked
        update()

    comparison_select.on_value_change(on_comparison_change)
    label_toggle.on_value_change(update)
    string_set_toggle.on_value_change(update)
    ui.on(CHORD_CLICK_EVENT, on_chord_click)
    update()


def main() -> None:
    ui.run(root, title="Fretboard scale visualiser", reload=False)


if __name__ in {"__main__", "__mp_main__"}:
    main()
